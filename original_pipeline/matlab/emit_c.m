function emit_c(S, Q, scales, outDir)
%EMIT_C  Write a self-contained C implementation of the trained network.
%
%   emit_c(S, Q, SCALES, OUTDIR) writes ann_predict.h, ann_predict_data.c and
%   ann_predict.c into OUTDIR.  S holds the float64 weights, Q the int8
%   quantised tensors and SCALES their per-tensor scale factors.
%
%   This is NOT MATLAB Coder output.  It is a hand-written generator that
%   implements the same explicit Wx+b forward pass that ann_predict.m
%   specifies, so that the C can be compiled and measured without a MATLAB
%   Coder licence.  Claims specific to Coder's own code remain unverified.
%
%   Two builds are supported from one source:
%     ANN_USE_INT8 = 1  int8 weights held in PROGMEM, dequantised per layer
%     ANN_USE_INT8 = 0  float32 weights held in PROGMEM
%   AVR builds read weights from flash; host builds read them from RAM.

names = {'W1','b1','W2','b2','W3','b3','W4','b4'};
dims  = [24 64; 1 64; 64 32; 1 32; 32 16; 1 16; 16 4; 1 4];

% ---------------------------------------------------------------- header
fid = fopen(fullfile(outDir, 'ann_predict.h'), 'w');
fprintf(fid, '/* ann_predict.h -- generated by emit_c.m. Do not edit.\n');
fprintf(fid, '   Forward pass of the 24-64-32-16-4 transmission-line fault classifier.\n');
fprintf(fid, '   Outputs are the flags [G C B A] in that order. */\n');
fprintf(fid, '#ifndef ANN_PREDICT_H\n#define ANN_PREDICT_H\n\n');
fprintf(fid, '#include <stdint.h>\n\n');
fprintf(fid, '#define ANN_N_IN   24\n');
fprintf(fid, '#define ANN_N_H1   64\n');
fprintf(fid, '#define ANN_N_H2   32\n');
fprintf(fid, '#define ANN_N_H3   16\n');
fprintf(fid, '#define ANN_N_OUT   4\n\n');
fprintf(fid, '#ifndef ANN_USE_INT8\n#define ANN_USE_INT8 1\n#endif\n\n');
fprintf(fid, 'typedef unsigned char boolean_T;\n\n');
fprintf(fid, '/* features: ANN_N_IN already-normalised inputs.\n');
fprintf(fid, '   flags   : ANN_N_OUT outputs, 1 where the sigmoid exceeds 0.5. */\n');
fprintf(fid, 'void ann_predict(const float features[ANN_N_IN],\n');
fprintf(fid, '                 boolean_T flags[ANN_N_OUT]);\n\n');
fprintf(fid, '/* Same forward pass, returning the raw sigmoid scores. */\n');
fprintf(fid, 'void ann_predict_scores(const float features[ANN_N_IN],\n');
fprintf(fid, '                        float scores[ANN_N_OUT]);\n\n');
fprintf(fid, '#endif /* ANN_PREDICT_H */\n');
fclose(fid);

% ------------------------------------------------------------- data file
fid = fopen(fullfile(outDir, 'ann_predict_data.c'), 'w');
fprintf(fid, '/* ann_predict_data.c -- generated by emit_c.m. Do not edit. */\n');
fprintf(fid, '#include "ann_predict.h"\n\n');
fprintf(fid, '#ifdef __AVR__\n#include <avr/pgmspace.h>\n');
fprintf(fid, '#else\n#define PROGMEM\n#endif\n\n');

fprintf(fid, '#if ANN_USE_INT8\n');
for k = 1:numel(names)
    nm = names{k};
    fprintf(fid, 'const float ann_scale_%s PROGMEM = %.10ef;\n', nm, scales(k));
end
fprintf(fid, '\n');
for k = 1:numel(names)
    nm = names{k};
    q  = Q.(nm);
    % Octave/MATLAB flatten column-major, but the C indexes W[i*n_out + j]
    % (row-major, the Keras [n_in][n_out] convention). Transpose so the two
    % agree; biases are vectors and are unaffected.
    if nm(1) == 'W', q = q.'; end
    write_array(fid, sprintf('ann_q%s', nm), int32(q(:)'), '%d', 'const int8_t', dims(k,:));
end
fprintf(fid, '\n#else /* float32 weights */\n\n');
for k = 1:numel(names)
    nm = names{k};
    w  = S.(nm);
    if nm(1) == 'W', w = w.'; end   % see the int8 branch above
    write_array(fid, sprintf('ann_f%s', nm), w(:)', '%.9ef', 'const float', dims(k,:));
end
fprintf(fid, '\n#endif\n');
fclose(fid);

% ------------------------------------------------------------- source
fid = fopen(fullfile(outDir, 'ann_predict.c'), 'w');
L = { ...
'/* ann_predict.c -- generated by emit_c.m. Do not edit.', ...
'   Explicit Wx+b forward pass, matching ann_predict.m exactly:', ...
'     a1 = relu(x  * W1 + b1)    24 -> 64', ...
'     a2 = relu(a1 * W2 + b2)    64 -> 32', ...
'     a3 = relu(a2 * W3 + b3)    32 -> 16', ...
'     p  = sigmoid(a3 * W4 + b4) 16 -> 4', ...
'   Keras stores Dense weights as [n_in][n_out], so the arrays below are', ...
'   indexed W[i*n_out + j] and the inner loop walks the input dimension. */', ...
'#include "ann_predict.h"', ...
'#include <math.h>', ...
'', ...
'#ifdef __AVR__', ...
'#include <avr/pgmspace.h>', ...
'#define RD_F(p) pgm_read_float(&(p))', ...
'#define RD_I(p) ((int8_t)pgm_read_byte(&(p)))', ...
'#else', ...
'#define RD_F(p) (p)', ...
'#define RD_I(p) (p)', ...
'#endif', ...
'', ...
'#if ANN_USE_INT8', ...
'extern const int8_t ann_qW1[], ann_qb1[], ann_qW2[], ann_qb2[];', ...
'extern const int8_t ann_qW3[], ann_qb3[], ann_qW4[], ann_qb4[];', ...
'extern const float ann_scale_W1, ann_scale_b1, ann_scale_W2, ann_scale_b2;', ...
'extern const float ann_scale_W3, ann_scale_b3, ann_scale_W4, ann_scale_b4;', ...
'#else', ...
'extern const float ann_fW1[], ann_fb1[], ann_fW2[], ann_fb2[];', ...
'extern const float ann_fW3[], ann_fb3[], ann_fW4[], ann_fb4[];', ...
'#endif', ...
'', ...
'/* One dense layer. W is [n_in][n_out] row-major; B is [n_out].', ...
'   use_int8 selects the quantised path, where sW and sB are the per-tensor', ...
'   scale factors of Eq. (21). relu applies the activation of Eq. (11). */', ...
'static void dense(const float *in, int n_in, float *out, int n_out,', ...
'                  const void *W, const void *B, float sW, float sB,', ...
'                  int use_int8, int relu)', ...
'{', ...
'    int i, j;', ...
'    for (j = 0; j < n_out; ++j) {', ...
'        float acc;', ...
'        if (use_int8) acc = (float)RD_I(((const int8_t *)B)[j]) * sB;', ...
'        else          acc = RD_F(((const float *)B)[j]);', ...
'        for (i = 0; i < n_in; ++i) {', ...
'            float w;', ...
'            if (use_int8) w = (float)RD_I(((const int8_t *)W)[i * n_out + j]) * sW;', ...
'            else          w = RD_F(((const float *)W)[i * n_out + j]);', ...
'            acc += in[i] * w;', ...
'        }', ...
'        if (relu && acc < 0.0f) acc = 0.0f;', ...
'        out[j] = acc;', ...
'    }', ...
'}', ...
'', ...
'void ann_predict_scores(const float features[ANN_N_IN], float scores[ANN_N_OUT])', ...
'{', ...
'    float a1[ANN_N_H1], a2[ANN_N_H2], a3[ANN_N_H3], z4[ANN_N_OUT];', ...
'    int j;', ...
'#if ANN_USE_INT8', ...
'    float s1 = RD_F(ann_scale_W1), sb1 = RD_F(ann_scale_b1);', ...
'    float s2 = RD_F(ann_scale_W2), sb2 = RD_F(ann_scale_b2);', ...
'    float s3 = RD_F(ann_scale_W3), sb3 = RD_F(ann_scale_b3);', ...
'    float s4 = RD_F(ann_scale_W4), sb4 = RD_F(ann_scale_b4);', ...
'    dense(features, ANN_N_IN, a1, ANN_N_H1, ann_qW1, ann_qb1, s1, sb1, 1, 1);', ...
'    dense(a1, ANN_N_H1, a2, ANN_N_H2, ann_qW2, ann_qb2, s2, sb2, 1, 1);', ...
'    dense(a2, ANN_N_H2, a3, ANN_N_H3, ann_qW3, ann_qb3, s3, sb3, 1, 1);', ...
'    dense(a3, ANN_N_H3, z4, ANN_N_OUT, ann_qW4, ann_qb4, s4, sb4, 1, 0);', ...
'#else', ...
'    dense(features, ANN_N_IN, a1, ANN_N_H1, ann_fW1, ann_fb1, 1.0f, 1.0f, 0, 1);', ...
'    dense(a1, ANN_N_H1, a2, ANN_N_H2, ann_fW2, ann_fb2, 1.0f, 1.0f, 0, 1);', ...
'    dense(a2, ANN_N_H2, a3, ANN_N_H3, ann_fW3, ann_fb3, 1.0f, 1.0f, 0, 1);', ...
'    dense(a3, ANN_N_H3, z4, ANN_N_OUT, ann_fW4, ann_fb4, 1.0f, 1.0f, 0, 0);', ...
'#endif', ...
'    for (j = 0; j < ANN_N_OUT; ++j)', ...
'        scores[j] = 1.0f / (1.0f + expf(-z4[j]));', ...
'}', ...
'', ...
'void ann_predict(const float features[ANN_N_IN], boolean_T flags[ANN_N_OUT])', ...
'{', ...
'    float s[ANN_N_OUT];', ...
'    int j;', ...
'    ann_predict_scores(features, s);', ...
'    for (j = 0; j < ANN_N_OUT; ++j) flags[j] = (s[j] > 0.5f) ? 1 : 0;', ...
'}' };
for k = 1:numel(L)
    fprintf(fid, '%s\n', L{k});
end
fclose(fid);
end

% ------------------------------------------------------------------ helper
function write_array(fid, name, vals, fmt, ctype, dim)
fprintf(fid, '/* %s : %dx%d */\n', name, dim(1), dim(2));
fprintf(fid, '%s %s[] PROGMEM = {\n  ', ctype, name);
for i = 1:numel(vals)
    fprintf(fid, fmt, vals(i));
    if i < numel(vals)
        fprintf(fid, ',');
        if mod(i, 12) == 0, fprintf(fid, '\n  '); else fprintf(fid, ' '); end
    end
end
fprintf(fid, '\n};\n\n');
end
